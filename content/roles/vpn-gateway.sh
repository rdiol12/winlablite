#!/bin/sh
# The cloud site's gateway on the Alpine node: address its adapters (NIC 0 on
# the site, NIC 1 on the WAN), forward between them, and build an IKEv2
# site-to-site tunnel with strongSwan to the other site's gateway (Windows
# RRAS in the office). The runner prepends WINLAB_NIC<i>_* and WINLAB_VPN_*
# variables (roles.sh_env): the peer's outside address, both sites' prefixes
# and the pre-shared key, which is the lab password. Nothing here is typed
# by hand, so the tunnel comes up the same way every time; the lesson is in
# reading it (swanctl --list-sas) and in building the office side.

role=vpn-gateway
done_dir=/var/lib/winlab/done
log() { echo "$(date '+%H:%M:%S')  [$role] $*"; }

command -v swanctl >/dev/null 2>&1 || { echo 'strongswan missing from the image (apk add strongswan at preparation)' >&2; exit 1; }
[ -n "$WINLAB_VPN_PEER" ] || { echo 'this machine is no site gateway: set [[site]] gateway in the lab' >&2; exit 1; }

# Adapters: ethN carries NIC N. The WAN one gets the default route; the site
# prefixes behind the router stay reachable through the inside adapter.
inside=""; outside=""
i=0
while [ $i -lt 8 ]; do
    eval ip="\$WINLAB_NIC${i}_IP"; eval prefix="\$WINLAB_NIC${i}_PREFIX"
    eval gw="\$WINLAB_NIC${i}_GW"; eval wan="\$WINLAB_NIC${i}_WAN"
    [ -n "$ip" ] || { i=$((i+1)); continue; }
    ifc="eth$i"
    ip link set "$ifc" up
    ip addr replace "$ip/$prefix" dev "$ifc" || exit 1
    if [ "$wan" = "1" ]; then
        outside="$ifc"; ip route replace default via "$gw" dev "$ifc" || exit 1
        log "outside $ifc $ip/$prefix, default via $gw"
    else
        inside="$ifc"; inside_gw="$gw"
        log "inside $ifc $ip/$prefix"
    fi
    i=$((i+1))
done
for p in $WINLAB_VPN_LOCAL_SUBNETS; do
    [ -n "$inside_gw" ] && ip route replace "$p" via "$inside_gw" dev "$inside" 2>/dev/null
done
sysctl -w net.ipv4.ip_forward=1 >/dev/null

local_ts=$(echo $WINLAB_VPN_LOCAL_SUBNETS | tr ' ' ',')
remote_ts=$(echo $WINLAB_VPN_REMOTE_SUBNETS | tr ' ' ',')
mkdir -p /etc/swanctl/conf.d
cat > /etc/swanctl/conf.d/winlab.conf <<CONF
# generated by winlab: site-to-site IKEv2 to $WINLAB_VPN_PEER_NODE
connections {
    site {
        version = 2
        local_addrs = $WINLAB_VPN_LOCAL_IP
        remote_addrs = $WINLAB_VPN_PEER
        proposals = aes256-sha256-modp2048,aes256-sha1-modp1024,aes128-sha1-modp1024,aes256-sha256-modp1024
        dpd_delay = 30s
        local { auth = psk
                id = $WINLAB_VPN_LOCAL_IP }
        remote { auth = psk
                 id = $WINLAB_VPN_PEER }
        children {
            site {
                local_ts = $local_ts
                remote_ts = $remote_ts
                esp_proposals = aes256-sha256,aes256-sha1,aes128-sha1,aes256gcm16
                start_action = start
                dpd_action = restart
                close_action = start
            }
        }
    }
}
secrets {
    ike-site {
        id-1 = $WINLAB_VPN_LOCAL_IP
        id-2 = $WINLAB_VPN_PEER
        secret = "$WINLAB_VPN_PSK"
    }
}
CONF
chmod 600 /etc/swanctl/conf.d/winlab.conf

# charon: the OpenRC service where the package provides one, else by hand.
if ! pgrep -x charon >/dev/null 2>&1; then
    rc-service strongswan start >/dev/null 2>&1 || /usr/lib/strongswan/charon >/dev/null 2>&1 &
    sleep 2
fi
swanctl --load-all >/dev/null 2>&1 || { sleep 3; swanctl --load-all || exit 1; }
swanctl --initiate --child site >/dev/null 2>&1 || true
mkdir -p "$done_dir"; : > "$done_dir/$role"
log "tunnel to $WINLAB_VPN_PEER_NODE ($WINLAB_VPN_PEER) for $WINLAB_VPN_REMOTE_SUBNETS loaded; swanctl --list-sas shows it"
